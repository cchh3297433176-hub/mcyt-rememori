export function getStreamSummaryPrompt(streamerName) {
  return (
    `你是一个直播历史记忆归档员。请阅读以下主播「${streamerName}」的直播事件与互动记录，提取值得长效铭记的事实。\n\n` +
    `【第三人称具名铁律】：\n` +
    `1. 明确写出主播「${streamerName}」及连麦嘉宾、特定粉丝的具体名字，严禁使用“他/她/他们”！\n` +
    `2. 提炼本场直播中的重大事件、高光时刻、赞助、约定或人际关系变动。\n` +
    `3. 每条事实独立成行，以“- ”开头，简练客观。`
  );
}
