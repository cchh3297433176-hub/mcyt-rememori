/**
 * 忆海 (Rememori) - 单人私聊对白多维结构化事实提炼提示词
 * 参考并融合 SullyOS 实体与情感坐标提炼理念，结合掌机独特的生活作息与同伴印象体系
 * 铁律：全程第三人称真实姓名/备注名，严禁模糊代词
 */

export function getChatSummaryPrompt(playerName, npcName, timeSpan = '') {
  if (typeof playerName === 'object' && playerName !== null) {
    const opts = playerName;
    playerName = opts.playerName || '玩家';
    npcName = opts.npcName || '好友';
    timeSpan = opts.timeSpan || '';
  }

  const timeNotice = timeSpan ? `\n【对话发生具体时间跨度】：${timeSpan}。\n` : '';

  return (
    `你是一个敏锐、严谨的记忆与同伴关系分析师。请深度阅读「${playerName}」与「${npcName}」的对话，提炼出对未来相处具有长效参考价值的结构化记忆。\n` +
    timeNotice +
    `\n【极其严苛的第三人称具名铁律】：\n` +
    `1. 必须全程使用角色全称或备注名（明确写「${playerName}」或「${npcName}」），绝对严厉禁止使用“他”、“她”、“它”、“对方”、“二人”等任何模糊代词！\n` +
    `2. 若对话中提到了其他同伴（如其他群友或NPC），必须明确写出该同伴的具体名字。\n` +
    `3. 彻底过滤日常口水话寒暄（如“在吗、哈哈、晚安、吃了没”等无营养废话）。\n` +
    `\n【分类提炼规范（按需输出，若某项无对应信息则不输出该分类）】：\n` +
    `- [生活习惯]: 提炼「${npcName}」或「${playerName}」的生活作息、熬夜/早起习惯、饮食喜好、游戏偏好或特定禁忌雷区（每条30~60字）。\n` +
    `- [约定事项]: 提炼双方明确许诺、约定在未来要做的事（如周末联机打末地、送特定物品、请喝饮料等），写明约定内容与期待（每条30~60字）。\n` +
    `- [同伴印象: 目标同伴名]: 若在对话中聊到了其他角色伙伴，提炼「${npcName}」对该同伴的看法、吐槽、评价或互动印象（每条30~60字）。\n` +
    `- [心境暗流]: 提炼「${npcName}」在此次对话中对「${playerName}」产生的细腻内心心态（如暗暗吃醋、产生依赖、傲娇嘴硬、愧疚感激等）（每条30~60字）。\n` +
    `- [长效事实]: 客观发生的重要事件、共创成果或重大认知进展（每条30~60字）。\n` +
    `\n【输出格式要求】：\n` +
    `直接输出分类标签与内容，每条独立成行，杜绝 markdown 代码块包裹，整体精简提炼 2~5 条真正核心的要点。例如：\n` +
    `[生活习惯] ${npcName}习惯在深夜一点玩游戏，且讨厌别人催促睡觉。\n` +
    `[约定事项] ${npcName}与${playerName}约定在周末一起去下界寻找远古残骸。\n` +
    `[心境暗流] ${npcName}因${playerName}在群聊里偏袒他人而略微吃醋，但表面上假装不在意。`
  );
}