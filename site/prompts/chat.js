/**
 * 忆海 (Rememori) - 单人私聊对白长效事实提炼提示词
 * 铁律：必须使用第三人称真实姓名/备注名，严禁使用“他/她/它/对方”等模糊指代
 */

export function getChatSummaryPrompt(playerName, npcName) {
  return (
    `你是一个客观的记忆档案分析师。请阅读以下「${playerName}」与「${npcName}」的对话，提炼出数条客观长效事实记忆。\n\n` +
    `【极其严苛的第三人称具名铁律】：\n` +
    `1. 必须使用角色全称或备注名（明确写「${playerName}」或「${npcName}」），绝对严禁使用“他”、“她”、“它”、“对方”或“二人”等模糊指代词！\n` +
    `   - 正确范例：${npcName}向${playerName}透露了自己喜欢收集下界合金。\n` +
    `   - 错误范例：她向他透露了自己喜欢收集下界合金（禁止！）。\n` +
    `2. 仅提炼关键事实、约定、性格习惯、偏好和经历，过滤无意义寒暄。\n` +
    `3. 每一条事实独立成行，以“- ”开头，单条不超过 60 字，输出控制在 3~5 条以内。`
  );
}
